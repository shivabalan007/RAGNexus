from __future__ import annotations

import hashlib
import os
import tempfile
from pathlib import Path
from uuid import uuid4


class S3DocumentStorage:
    """S3-backed original-file storage. resolve() materializes a temporary worker copy."""

    def __init__(self, bucket: str, region: str | None = None, prefix: str = "ragnexus"):
        if not bucket:
            raise ValueError("S3_BUCKET is required when STORAGE_BACKEND=s3")
        try:
            import boto3
        except ImportError as exc:
            raise RuntimeError("Install boto3 to use S3 document storage") from exc
        self.bucket = bucket
        self.prefix = prefix.strip("/")
        self.client = boto3.client("s3", region_name=region or None)
        self.cache_dir = Path(tempfile.gettempdir()) / "ragnexus-s3-cache"
        self.cache_dir.mkdir(parents=True, exist_ok=True)

    def save_stream(self, stream, *, workspace_id: str, max_bytes: int):
        digest = hashlib.sha256()
        size = 0
        tmp = self.cache_dir / f"upload-{uuid4().hex}.tmp"
        try:
            with tmp.open("xb") as target:
                while True:
                    block = stream.read(1024 * 1024)
                    if not block:
                        break
                    size += len(block)
                    if size > max_bytes:
                        raise ValueError(f"File exceeds maximum upload size of {max_bytes} bytes")
                    digest.update(block)
                    target.write(block)
            if size == 0:
                raise ValueError("Uploaded file is empty")
            key = f"{self.prefix}/{workspace_id}/{uuid4().hex}.bin"
            self.client.upload_file(str(tmp), self.bucket, key, ExtraArgs={"ServerSideEncryption": "AES256"})
            return key, digest.hexdigest(), size
        finally:
            tmp.unlink(missing_ok=True)

    def resolve(self, object_key: str) -> Path:
        # Never accept arbitrary bucket URLs; keys are generated by this adapter.
        key = object_key.lstrip("/")
        if not key.startswith(f"{self.prefix}/") or ".." in Path(key).parts:
            raise ValueError("Invalid S3 object key")
        local = self.cache_dir / f"{hashlib.sha256(key.encode()).hexdigest()}.bin"
        self.client.download_file(self.bucket, key, str(local))
        return local

    def delete(self, path_or_key: str | Path) -> None:
        key = str(path_or_key)
        if key.startswith(f"{self.prefix}/"):
            self.client.delete_object(Bucket=self.bucket, Key=key)
        else:
            Path(path_or_key).unlink(missing_ok=True)
